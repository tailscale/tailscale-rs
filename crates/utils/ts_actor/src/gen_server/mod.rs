/// Start a new [`GenServer`] defined by behavior `B` and with the given `args`.
///
/// Returns a [`ProcFut`] to run the [`GenServer`].
pub fn start<B>(behavior: B, args: B::Args) -> impl FnOnce(ProcContext) -> StaticStorage<ProcFut>
where
    B: GenServer + 'static,
{
    move |ctx| {
        StaticStorage::Box(Box::new(async move {
            let (mut state, mut action) = behavior.init(&ctx, args).await?;

            loop {
                let timeout = match action.take() {
                    Some(Action::Continue) => {
                        action = behavior.handle_continue(&ctx, &mut state).await;
                        continue;
                    }
                    Some(Action::Stop) => {
                        return Ok(());
                    }
                    Some(Action::Timeout(dur)) => Some(dur),
                    None => None,
                };

                let rt = ctx.rt()?;
                let msg = futures_util::select_biased! {
                    rx = ctx.recv().fuse() => {
                        rx?
                    },
                    _ = crate::util::option_timeout(rt.executor(), timeout).fuse() => {
                        tracing::debug!("genserver timed out");
                        ctx.try_send(&ctx.pid(), crate::message![Timeout(())]).await?;
                        continue;
                    }
                };

                msg_match! [
                    msg,
                    Call: Call { rf, msg, sender } => {
                        let (reply, resp_action)  = behavior.handle_call(&ctx, &mut state, msg, ReplyHandle {
                            pid: sender,
                            rf,
                        }).await;

                        action = resp_action;

                        if let Some(reply) = reply {
                            reply.send(&ctx).await;
                        }
                    },
                    Cast: Cast(msg) => {
                        action = behavior.handle_cast(&ctx, &mut state, msg).await;
                    },
                    else msg => {
                        action = behavior.handle_info(&ctx, &mut state, msg).await;
                    }
                ]
            }
        }))
    }
}

/// Send a request to the [`GenServer`] identified by `server`, waiting for its reply.
pub async fn call(
    ctx: &ProcContext,
    server: &dyn ToProcName,
    msg: Message,
) -> Result<Message, Error> {
    let rf = ctx.new_ref()?;

    ctx.send(
        server,
        crate::message![Call {
            rf,
            msg,
            sender: ctx.this_pid,
        }],
    )
    .await?;

    let msg = ctx
        .recv_where(|msg| {
            let Some(rep) = msg.downcast_ref::<CallReply>() else {
                tracing::trace!("msg no match");
                return false;
            };

            rep.rf == rf
        })
        .await?;

    // unwrap: established above that this is indeed a `CallReply`
    let reply = msg.downcast::<CallReply>().unwrap();

    Ok(reply.msg)
}

/// Send a message to the server identified by `server`.
///
/// Unlike Erlang, error conditions from a full mailbox or the pid not existing are not
/// simply ignored. This function waits for space in them mailbox and reports if the target
/// genserver doesn't exist.
pub async fn cast(ctx: &ProcContext, server: &dyn ToProcName, msg: Message) -> Result<(), Error> {
    ctx.send(server, crate::message![Cast(msg)]).await
}

/// Try to send a message to the server identified by `server` without waiting for space in
/// the target process's mailbox.
///
/// Unlike Erlang, error conditions from the pid not existing are not simply ignored: this
/// function returns [`Error::NoProc`] in that case. Simply drop the result if you're not interested
/// in this condition.
pub async fn try_cast(
    ctx: &ProcContext,
    server: &dyn ToProcName,
    msg: Message,
) -> Result<(), Error> {
    ctx.try_send(server, crate::message![Cast(msg)])
        .await
        .map(|_| ())
}

/// Result alias for the return type of [`GenServer::handle_call`].
pub type CallResult = (Option<Reply>, Option<Action>);

/// Defines a process which handles messages in request-response style, i.e. like a server.
pub trait GenServer: Send {
    /// Arguments for initializing the server.
    type Args: Send;
    /// State carried by the server handed by `&mut` into each callback.
    type State: Send;

    /// Initialize the genserver.
    ///
    /// Invoked automatically by [`start`].
    fn init(
        &self,
        ctx: &ProcContext,
        args: Self::Args,
    ) -> impl Future<Output = Result<(Self::State, Option<Action>), Error>> + Send;

    /// Handle a request from another process.
    ///
    /// A reply is expected; `handle` expresses this. If you [`ReplyHandle::commit`] it and
    /// return it, the `gen_server` logic handles sending it for you. If you need to defer
    /// your reply, you can store the handle and call [`ReplyHandle::reply`] to respond
    /// later.
    fn handle_call(
        &self,
        ctx: &ProcContext,
        state: &mut Self::State,
        message: Message,
        handle: ReplyHandle,
    ) -> impl Future<Output = (Option<Reply>, Option<Action>)> + Send {
        _ = ctx;
        _ = handle;
        _ = state;
        drop(message);

        async move { (Some(handle.commit(Default::default())), None) }
    }

    /// Handle a one-way message from another process. Replies are not possible.
    ///
    /// The difference between this and [`GenServer::handle_info`] is that cast messages are
    /// deliberately sent via [`GenServer`] machinery, while info messages are a catchall
    /// for everything else.
    fn handle_cast(
        &self,
        ctx: &ProcContext,
        state: &mut Self::State,
        message: Message,
    ) -> impl Future<Output = Option<Action>> + Send {
        _ = ctx;
        _ = state;
        drop(message);

        async move { None }
    }

    /// Handle a message which isn't a call or cast.
    ///
    /// Any messages sent to this process which aren't aware of [`GenServer`] semantics are
    /// routed to this method. If you need to handle
    /// [`SystemMessage`][crate::SystemMessage], for instance, those appear here.
    fn handle_info(
        &self,
        ctx: &ProcContext,
        state: &mut Self::State,
        message: Message,
    ) -> impl Future<Output = Option<Action>> + Send {
        _ = ctx;
        _ = state;
        drop(message);

        async move { None }
    }

    /// Handle [`Action::Continue`].
    ///
    /// This allows behavior to continue running without blocking a message handler.
    fn handle_continue(
        &self,
        ctx: &ProcContext,
        state: &mut Self::State,
    ) -> impl Future<Output = Option<Action>> + Send {
        _ = ctx;
        _ = state;
        async move { None }
    }
}

impl<B> GenServer for &B
where
    B: GenServer + Sync,
{
    type Args = B::Args;
    type State = B::State;

    async fn init(
        &self,
        ctx: &ProcContext,
        args: Self::Args,
    ) -> Result<(Self::State, Option<Action>), Error> {
        B::init(self, ctx, args).await
    }

    fn handle_call(
        &self,
        ctx: &ProcContext,
        state: &mut Self::State,
        message: Message,
        caller_handle: ReplyHandle,
    ) -> impl Future<Output = (Option<Reply>, Option<Action>)> + Send {
        B::handle_call(self, ctx, state, message, caller_handle)
    }

    fn handle_cast(
        &self,
        ctx: &ProcContext,
        state: &mut Self::State,
        message: Message,
    ) -> impl Future<Output = Option<Action>> + Send {
        B::handle_cast(self, ctx, state, message)
    }

    fn handle_info(
        &self,
        ctx: &ProcContext,
        state: &mut Self::State,
        message: Message,
    ) -> impl Future<Output = Option<Action>> + Send {
        B::handle_info(self, ctx, state, message)
    }

    fn handle_continue(
        &self,
        ctx: &ProcContext,
        state: &mut Self::State,
    ) -> impl Future<Output = Option<Action>> + Send {
        B::handle_continue(self, ctx, state)
    }
}

/// Lightweight handle to a caller which the implementer of [`GenServer::handle_call`] can
/// hold in order to reply later.
///
/// The intended semantics of [`GenServer::handle_call`] are that each call gets exactly
/// one reply; hence, [`ReplyHandle::reply`] and [`ReplyHandle::commit`] both consume
/// `self` (you must pick one behavior).
#[must_use = "not consuming a caller handle will cause the call to hang"]
#[derive(Debug, Copy, Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct ReplyHandle {
    pid: Pid,
    rf: Ref,
}

impl ReplyHandle {
    /// Send a reply to the caller.
    pub async fn reply(self, ctx: &ProcContext, msg: Message) {
        self.commit(msg).send(ctx).await
    }

    /// Commit this handle to a [`Reply`].
    pub const fn commit(self, message: Message) -> Reply {
        Reply::new(self, message)
    }
}

/// An [`Action::Timeout`] occurred.
///
/// This is delivered as an info message.
#[derive(Debug)]
pub struct Timeout(());

/// Actions which may occur as a result of a [`GenServer`] handler.
#[derive(Debug, Copy, Clone, PartialEq, Eq)]
pub enum Action {
    /// Stop the [`GenServer`] normally.
    Stop,

    /// Set a timeout.
    ///
    /// If the timeout elapses before another message is handled, a [`Timeout`] info message
    /// is delivered to the [`GenServer`].
    // TODO(npry): support user-provided timeout messages
    Timeout(Duration),

    /// Invoke [`GenServer::handle_continue`] immediately after this handler.
    ///
    /// This allows sending a reply immediately and continuing to perform additional
    /// processing afterward.
    Continue,
}

/// Reply to a genserver call message.
///
/// This is typically returned by [`ReplyHandle::commit`] in [`GenServer::handle_call`].
#[must_use = "an unsent Reply will leave the caller waiting forever"]
pub struct Reply(ReplyHandle, Message);

impl Reply {
    /// Construct a new [`Reply`] from a handle and a message.
    pub const fn new(handle: ReplyHandle, message: Message) -> Self {
        Self(handle, message)
    }

    /// Attempt to send this [`Reply`].
    ///
    /// The message is just dropped if the reply doesn't go through because of a full mailbox.
    pub async fn send(self, ctx: &ProcContext) {
        let Reply(ReplyHandle { pid, rf }, msg) = self;

        if let Err(e) = ctx
            .try_send(&pid, crate::message![CallReply { rf, msg }])
            .await
        {
            tracing::error!(error = %e, "replying to call");
        }
    }
}

impl From<Reply> for CallResult {
    fn from(value: Reply) -> Self {
        (Some(value), None)
    }
}

struct Call {
    rf: Ref,
    msg: Message,
    sender: Pid,
}

struct CallReply {
    rf: Ref,
    msg: Message,
}

struct Cast(Message);
