//! Adaptation of Erlang's `gen_server`: processes that send and receive messages like RPCs, i.e.
//! they act like servers within the actor system.
//!
//! Implementing the [`GenServer`] trait allows the type be [`start`]ed as a process. The genserver
//! may then be sent request-response messages via [`call`] and [`cast`]. `call` messages expect a
//! reply, while `cast` messages do not (think "casting" a fishing line -- unidirectional).
//! Genservers term all other messages (not sent via [`call`] or [`cast`]) "info" messages.
//!
//! Note that it is _only_ possible to call and cast messages via the [`call`] and [`cast`]
//! functions in this module (and their `typed` equivalents): these wrap and unwrap the messages
//! and replies in private types under the hood to disambiguate them from infos.
//!
//! # `typed`
//!
//! The `typed` module provides a way to prove that a [`GenServer`] implementation can handle a
//! given call, cast, or info type (via [`TypedCall`], [`TypedCast`], and [`TypedInfo`]), and
//! encodes the reply type for a call. Using the typed traits allows most of the [`GenServer`]
//! implementation to be generated by using the [`typed_call!`][crate::typed_call],
//! [`typed_cast!`][crate::typed_cast], and [`typed_info!`][crate::typed_info] macros, which
//! expand out into a [`msg_match!`] plus an invocation of the relevant trait method for
//! each named type. The helpers [`call_typed`] and [`cast_typed`] handle (un)wrapping
//! arguments and replies into [`Message`]s automatically.

